#include <iostream>

int main() {

    // tipe data number
    // int (integer) bilang bulat entah positif atau negatif
    // float adalah bilangan desimal atau koma
    // double adalah bilangan desimal atau koma dengan presisi lebih tinggi dari float
    
    int a = 23;
    std::cout << a << std::endl;
    
    float b = 22.5;
    std::cout << b << std::endl;
    
    double c = 33.7;
    std::cout << c << std::endl;

}